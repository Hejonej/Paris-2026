const assert = require('node:assert/strict');
const A = require('../recommendation-actions-v1.js');
const place={name:'Ofr. Paris',placeId:'ofr-paris',address:'Paris'};
const trip={saved:[],recommendationCandidates:[],plan:{days:[{items:[],nearby:[],backup:[]}]}};
const base=JSON.stringify(trip);
const candidate=A.applyApproved(trip,{type:'ADD_CANDIDATE',place});
assert.equal(candidate.next.recommendationCandidates.length,1);
assert.equal(candidate.next.plan.days[0].items.length,0);
assert.equal(JSON.stringify(trip),base,'original state must stay unchanged');
assert.deepEqual(candidate.undo,trip);
assert.throws(()=>A.prepareAction(candidate.next,{type:'ADD_CANDIDATE',place}),/ALREADY_CANDIDATE/);
assert.throws(()=>A.prepareAction(trip,{type:'SCHEDULE',place,dayIndex:0}),/VERIFICATION_REQUIRED/);
assert.throws(()=>A.prepareAction(trip,{type:'SCHEDULE',place,dayIndex:9,verified:true}),/INVALID_DAY/);
const added=A.applyApproved(candidate.next,{type:'SCHEDULE',place,dayIndex:0,verified:true});
assert.equal(added.next.plan.days[0].items.length,1);
assert.equal(added.next.recommendationCandidates.length,0);
assert.equal(added.undo.recommendationCandidates.length,1);
assert.throws(()=>A.prepareAction(added.next,{type:'SCHEDULE',place,dayIndex:0,verified:true}),/ALREADY_IN_PLAN/);
assert.equal(A.cta('fill_slot').primary,'이 시간에 추가');
assert.equal(A.cta('explore').primary,'여행 후보에 추가');
console.log('Recommendation action contract: all tests passed');
